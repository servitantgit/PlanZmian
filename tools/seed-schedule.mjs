#!/usr/bin/env node
/* ================================================================
   tools/seed-schedule.mjs — one-off seed of the 2026 factory schedule
   into migrations/seed_2026.sql (SPEC 13.1, Phase 1.5).

   Loads js/schedules/gillette/2026.js through node:vm with stub
   registerSchedule / registerYearData and writes a SQL INSERT for
   schedule_years with revision = 1 and updated_by = 'seed'.

   HOURS ARE TAKEN VERBATIM FROM THE FILE — never recomputed.
   October / brigade A = 160 on purpose.

   Usage:
     node tools/seed-schedule.mjs           # writes migrations/seed_2026.sql
     node tools/seed-schedule.mjs --print   # prints SQL to stdout only
   ================================================================ */

import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE_FILE = path.join(ROOT, 'js', 'schedules', 'gillette', '2026.js');
const OUT_FILE = path.join(ROOT, 'migrations', 'seed_2026.sql');

const SCHEDULE_ID = 'gillette';
const REVISION = 1;
const UPDATED_BY = 'seed';
const UPDATED_AT = new Date().toISOString();

/**
 * Executes 2026.js in a vm sandbox and returns everything it registered.
 * @returns {{ year: number, data: object, hours: object }}
 */
export function loadSchedule2026() {
  const code = fs.readFileSync(SOURCE_FILE, 'utf8');
  let captured = null;

  const sandbox = {
    console: { log() {}, warn() {}, error() {} },
    registerSchedule() {},
    registerYearData(scheduleId, year, data, hours) {
      if (scheduleId !== SCHEDULE_ID) return;
      if (captured && captured.year === year) return;
      captured = { year, data, hours };
    },
  };

  vm.createContext(sandbox);
  vm.runInContext(code, sandbox, { filename: SOURCE_FILE });

  if (!captured) {
    throw new Error('2026.js did not call registerYearData() for "' + SCHEDULE_ID + '"');
  }
  return captured;
}

function sqlQuote(value) {
  return "'" + String(value).replace(/'/g, "''") + "'";
}

/**
 * Builds the SQL text for the seed.
 * @param {{ year:number, data:object, hours:object }} schedule
 * @returns {string}
 */
export function buildSeedSql(schedule) {
  const dataJson = JSON.stringify(schedule.data);
  const hoursJson = JSON.stringify(schedule.hours);

  return [
    '-- Generated by tools/seed-schedule.mjs — DO NOT EDIT BY HAND.',
    '-- Hours are copied verbatim from js/schedules/gillette/' +
      schedule.year +
      '.js',
    '-- (October / brigade A = 160 is intentional, do not recompute).',
    'INSERT INTO schedule_years',
    '  (schedule_id, year, data_json, hours_json, revision, updated_at, updated_by)',
    'VALUES (',
    '  ' + sqlQuote(SCHEDULE_ID) + ',',
    '  ' + schedule.year + ',',
    '  ' + sqlQuote(dataJson) + ',',
    '  ' + sqlQuote(hoursJson) + ',',
    '  ' + REVISION + ',',
    '  ' + sqlQuote(UPDATED_AT) + ',',
    '  ' + sqlQuote(UPDATED_BY),
    ')',
    ';',
    '',
  ].join('\n');
}

function main() {
  const schedule = loadSchedule2026();
  const sql = buildSeedSql(schedule);

  if (process.argv.includes('--print')) {
    process.stdout.write(sql);
    return;
  }

  fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
  fs.writeFileSync(OUT_FILE, sql, 'utf8');
  console.log(
    'Seed SQL written: ' +
      path.relative(ROOT, OUT_FILE) +
      ' (year ' +
      schedule.year +
      ', revision ' +
      REVISION +
      ', updated_by ' +
      UPDATED_BY +
      ')'
  );
}

// Only run when executed directly, so tests can import the helpers above.
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
